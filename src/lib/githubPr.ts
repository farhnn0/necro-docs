import { parseGitHubUrl, scanSource } from '@/lib/repoAnalyzer';
import { isPatchable } from '@/lib/types';

export type PrErrorCode =
  | 'INVALID_REQUEST' | 'MISSING_TOKEN' | 'INVALID_TOKEN' | 'NO_PUSH_ACCESS' | 'NOT_FOUND'
  | 'FILE_MISMATCH' | 'NO_CHANGES' | 'RATE_LIMITED' | 'GITHUB_ERROR';

export class PrError extends Error {
  constructor(readonly code: PrErrorCode, message: string, readonly status: number) { super(message); }
}

export interface PrParams {
  repositoryUrl: string;
  filePath: string;
  /** File as analyzed. Must match GitHub's copy, otherwise the commit could overwrite a truncated or changed file. */
  originalCode: string;
  patchedCode: string;
  summary: string;
  rotScore?: number;
  token: string;
}
export interface PrResult { prNumber: number; prUrl: string; branch: string }

const API = 'https://api.github.com';
const MAX_FILE_CHARS = 200_000;
const lf = (text: string) => text.replace(/\r\n?/g, '\n');

/** Repo-relative path without traversal. Throws PrError otherwise. */
export function safeFilePath(input: unknown): string {
  const path = typeof input === 'string' ? input.trim().replace(/\\/g, '/').replace(/^\/+/, '') : '';
  if (!path || path.length > 500 || path.split('/').some((part) => !part || part === '.' || part === '..')) {
    throw new PrError('INVALID_REQUEST', 'filePath must be a repository-relative file path.', 400);
  }
  return path;
}

const encodePath = (path: string) => path.split('/').map(encodeURIComponent).join('/');

export function branchNameFor(filePath: string, now = Date.now()): string {
  const base = (filePath.split('/').pop() ?? 'file').replace(/\.[^.]+$/, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40) || 'file';
  return `necro/fix-${base}-${now.toString(36)}`;
}

/** Keep the file's own line endings and trailing newline so the PR diff only shows real changes. */
export function matchStyle(remote: string, patched: string): string {
  let out = lf(patched);
  const endsWithNewline = lf(remote).endsWith('\n');
  if (endsWithNewline && !out.endsWith('\n')) out += '\n';
  if (!endsWithNewline) out = out.replace(/\n+$/, '');
  return remote.includes('\r\n') ? out.replace(/\n/g, '\r\n') : out;
}

const oneLine = (text: string, max: number) => text.replace(/\s+/g, ' ').trim().slice(0, max);
const bullets = (items: string[] = []) => items.slice(0, 20).map((item) => oneLine(item, 300)).filter(Boolean).map((item) => `- ${item}`);

export function prTitle(filePath: string, fixedCount = 0): string {
  const fileName = filePath.split('/').pop() ?? filePath;
  return fixedCount > 0 ? `fix(${fileName}): resolve ${fixedCount} audit finding${fixedCount === 1 ? '' : 's'}` : `fix(${fileName}): apply audit fix`;
}

export function prBody({ filePath, summary, rotScore, fixed, remaining }: Pick<PrParams, 'filePath' | 'summary' | 'rotScore'> & { fixed?: string[]; remaining?: string[] }): string {
  const fixedLines = bullets(fixed);
  const remainingLines = bullets(remaining);
  return [
    '## Summary',
    '',
    oneLine(summary, 1000) || 'Local fix generated by the NecroDocs AI patch.',
    '',
    `File: \`${filePath}\`${typeof rotScore === 'number' ? ` (rot score before: ${Math.round(rotScore)}/100)` : ''}`,
    '',
    ...(fixedLines.length ? ['**Fixed** (gone in a re-scan of the patched file):', ...fixedLines, ''] : []),
    ...(remainingLines.length ? ['**Not changed** (still reported after the patch):', ...remainingLines, ''] : []),
    '## Review & Testing Checklist for Human',
    '',
    '- [ ] Read the diff: only the lines at the findings above should change.',
    `- [ ] Type-check and run the tests. Files that import \`${filePath}\` were not compiled against this change.`,
    '',
    '### Notes',
    '',
    "- Written by an AI model. NecroDocs checked it only by re-scanning this file; the project was not built or run.",
    '',
    '---',
    '',
    '*Opened by [NecroDocs](https://github.com/farhnn0/necro-docs)*',
  ].join('\n');
}

type Fetch = typeof fetch;

export async function createPullRequest(params: PrParams, fetchImpl: Fetch = fetch): Promise<PrResult> {
  const { owner, repo } = (() => {
    try { return parseGitHubUrl(params.repositoryUrl); } catch { throw new PrError('INVALID_REQUEST', 'repositoryUrl must be a GitHub repository.', 400); }
  })();
  const filePath = safeFilePath(params.filePath);
  if (!params.patchedCode.trim() || params.patchedCode.length > MAX_FILE_CHARS) throw new PrError('INVALID_REQUEST', 'patchedCode is empty or too large.', 400);
  const repoPath = `${API}/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}`;

  const gh = async <T>(url: string, init?: RequestInit): Promise<{ status: number; ok: boolean; data: T }> => {
    const response = await fetchImpl(url, {
      ...init,
      signal: AbortSignal.timeout(20_000),
      headers: {
        Accept: 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        Authorization: `Bearer ${params.token}`,
        ...(init?.body ? { 'Content-Type': 'application/json' } : {}),
      },
    });
    const data = await response.json().catch(() => ({})) as T;
    return { status: response.status, ok: response.ok, data };
  };
  const fail = (status: number, data: unknown, write = false): never => {
    const message = (data as { message?: string } | null)?.message ?? 'GitHub request failed.';
    if (status === 401) throw new PrError('INVALID_TOKEN', 'GitHub rejected the token.', 401);
    if (status === 429 || (status === 403 && /rate limit/i.test(message))) throw new PrError('RATE_LIMITED', 'GitHub rate limit reached. Try again later.', 429);
    if (status === 403 || (write && status === 404)) throw new PrError('NO_PUSH_ACCESS', 'This token cannot push to the repository.', 403);
    if (status === 404) throw new PrError('NOT_FOUND', 'Repository or file was not found.', 404);
    throw new PrError('GITHUB_ERROR', message, 502);
  };

  // 1. Repository + default branch. `permissions.push` is present for authenticated requests.
  const repoRes = await gh<{ default_branch?: string; permissions?: { push?: boolean } }>(repoPath);
  if (!repoRes.ok) fail(repoRes.status, repoRes.data);
  if (repoRes.data.permissions?.push === false) throw new PrError('NO_PUSH_ACCESS', 'This token cannot push to the repository.', 403);
  const base = repoRes.data.default_branch;
  if (!base) throw new PrError('GITHUB_ERROR', 'Could not read the default branch.', 502);

  // 2. Head commit of the default branch.
  const refRes = await gh<{ object?: { sha?: string } }>(`${repoPath}/git/ref/heads/${encodePath(base)}`);
  if (!refRes.ok) fail(refRes.status, refRes.data);
  const headSha = refRes.data.object?.sha;
  if (!headSha) throw new PrError('GITHUB_ERROR', 'Could not read the latest commit.', 502);

  // 3. Current file at that commit. Checked before creating a branch so a refusal leaves nothing behind.
  const fileRes = await gh<{ type?: string; sha?: string; content?: string; encoding?: string }>(`${repoPath}/contents/${encodePath(filePath)}?ref=${headSha}`);
  if (!fileRes.ok) fail(fileRes.status, fileRes.data);
  const file = fileRes.data;
  if (file.type !== 'file' || !file.sha || file.encoding !== 'base64' || typeof file.content !== 'string') {
    throw new PrError('FILE_MISMATCH', 'The file is too large or is not a regular file, so it cannot be patched through the API.', 409);
  }
  const remote = Buffer.from(file.content, 'base64').toString('utf8');
  if (lf(remote).trimEnd() !== lf(params.originalCode).trimEnd()) {
    throw new PrError('FILE_MISMATCH', 'The file on GitHub differs from the analyzed snapshot (it changed, or the analyzed copy was truncated). Re-run the analysis before opening a PR.', 409);
  }
  const content = matchStyle(remote, params.patchedCode);
  if (content === remote) throw new PrError('NO_CHANGES', 'The patch does not change the file.', 422);
  // Scanned here, not taken from the caller, so the PR never claims a fix the scanner did not see.
  const after = scanSource(filePath, content).filter(isPatchable);
  const fixed = scanSource(filePath, remote).filter((finding) => isPatchable(finding) && !after.some((left) => left.kind === finding.kind)).map((finding) => finding.text);
  const remaining = after.map((finding) => finding.text);

  // 4. Branch.
  const branch = branchNameFor(filePath);
  const branchRes = await gh(`${repoPath}/git/refs`, { method: 'POST', body: JSON.stringify({ ref: `refs/heads/${branch}`, sha: headSha }) });
  if (!branchRes.ok) fail(branchRes.status, branchRes.data, true);

  const cleanup = () => gh(`${repoPath}/git/refs/heads/${encodePath(branch)}`, { method: 'DELETE' }).catch(() => undefined);
  const title = prTitle(filePath, fixed.length);
  try {
    // 5. Commit.
    const commitRes = await gh(`${repoPath}/contents/${encodePath(filePath)}`, {
      method: 'PUT',
      body: JSON.stringify({ message: title, content: Buffer.from(content, 'utf8').toString('base64'), branch, sha: file.sha }),
    });
    if (!commitRes.ok) fail(commitRes.status, commitRes.data, true);

    // 6. Pull request.
    const prRes = await gh<{ number?: number; html_url?: string }>(`${repoPath}/pulls`, {
      method: 'POST',
      body: JSON.stringify({ title, head: branch, base, body: prBody({ filePath, summary: params.summary, rotScore: params.rotScore, fixed, remaining }) }),
    });
    if (!prRes.ok) fail(prRes.status, prRes.data, true);
    if (typeof prRes.data.number !== 'number' || !prRes.data.html_url) throw new PrError('GITHUB_ERROR', 'GitHub did not return the pull request.', 502);
    return { prNumber: prRes.data.number, prUrl: prRes.data.html_url, branch };
  } catch (error) {
    await cleanup();
    throw error;
  }
}
